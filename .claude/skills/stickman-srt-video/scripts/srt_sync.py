"""SRT -> scenes.js sync for gen-stickman-v2.

Rewrites the block between `/* SRT:BEGIN */` and `/* SRT:END */` in a scenes file with:
  const C = [...]       cue start times (C[n-1] = start of cue n), last item = end of the final cue
  const SRT_TEXT = [...] cue text (for subtitles)
and reports the duration to pass to build.py (--duration). Run it whenever the SRT changes.

  python scripts/srt_sync.py <video>/<name>.srt <video>/scenes.js
"""
import json, re, sys

def parse(path):
    out = []
    for block in re.split(r"\n\s*\n", open(path, encoding="utf-8-sig").read().strip()):
        lines = block.strip().splitlines()
        m = re.match(r"(\d+):(\d+):(\d+)[,.](\d+)\s*-->\s*(\d+):(\d+):(\d+)[,.](\d+)", lines[1])
        g = list(map(int, m.groups()))
        out.append((g[0]*3600 + g[1]*60 + g[2] + g[3]/1000, g[4]*3600 + g[5]*60 + g[6] + g[7]/1000, " ".join(lines[2:])))
    return out

srt, scenes = sys.argv[1], sys.argv[2]
cues = parse(srt)
for a, b in zip(cues, cues[1:]):
    if abs(a[1] - b[0]) > 1e-6:
        print(f"warning: gap/overlap between cues at {a[1]} / {b[0]}")
C = [round(c[0], 3) for c in cues] + [round(cues[-1][1], 3)]
block = ("/* SRT:BEGIN (generated by tools/srt_sync.py; do not edit by hand) */\n"
         f"const C = {json.dumps(C)};\n"
         f"const SRT_TEXT = {json.dumps([c[2] for c in cues], ensure_ascii=False)};\n"
         "/* SRT:END */")
src = open(scenes, encoding="utf-8").read()
new, n = re.subn(r"/\* SRT:BEGIN.*?/\* SRT:END \*/", lambda _: block, src, flags=re.S)
if n != 1:
    sys.exit("scenes file needs exactly one /* SRT:BEGIN */ ... /* SRT:END */ block")
open(scenes, "w", encoding="utf-8").write(new)
print(f"synced {len(cues)} cues; duration {C[-1]}s")
