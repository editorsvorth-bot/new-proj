/* ======================================================================================
   SCENES: "<VIDEO TITLE>" (SRT-timed). Copy this file to <project>/videos/<slug>/scenes.js.
   Every on-screen word traces to a cue in <slug>.srt (see FLOW.md). Every scene boundary and reveal is on the
   SRT clock: cue(n) = start of cue n, wordAt(n, 'phrase') = when that phrase is spoken inside cue n.
   Helpers (spineBar, person, tieFigure, headlineWords, browserWin, qBubble, thread ...) come from the kit.
   ====================================================================================== */
let SCENES = [], CUES = [], SFX_CUES = [], STORYBOARD = [];

/* SRT:BEGIN (generated by scripts/srt_sync.py; do not edit by hand) */
const C = [];
const SRT_TEXT = [];
/* SRT:END */

const GY = 860;                       // ground line (feet)
const TR = 0.7, TRW = 1.0;            // iris length / wipe length: an incoming scene starts TR (or TRW) before its cue
// Spine object: one proportional bar that carries the script's structure. 1 figure = 1/SLOTS of the whole.
const BAR = { x: 260, w: 1400, h: 64 };
const SHARES = [0.2, 0.2, 0.6];        // <- from the script's numbers only; must sum to 1
const GROUP = ['GROUP A', 'GROUP B', 'GROUP C'];   // <- the script's own names, translated faithfully
const SLOTS = 10, SLOT = i => BAR.x + BAR.w / SLOTS / 2 + BAR.w / SLOTS * i;
const WEAR = ['bucket', 'capBack', 'specs', 'specs', 'beanie', 'bun', 'cap', 'none', 'bun', 'beanie'];  // looks per slot

function buildScenes() {
  SCENES = [
    /* 1. OPENING (cues 1-2): everyone walks in alike; the bar appears and cracks into its shares when the split is spoken.
          Nobody's kind (colour, accessory, label) is shown before its words are spoken. */
    { id: 'open', start: 0, end: cue(3) - .001,
      camera: t => tween([[0, { x: 0, y: 30, z: 1.06 }], [2.2, { x: 0, y: 0, z: 1 }]], t),
      draw(g, t, T, c) {
        NOW = t; dotGrid(g, c);
        world(g, c, () => {
          groundLine(g, GY, prog(t, 0, .8));
          spineBar(g, prog(t, cue(2), cue(2) + 1.2), SHARES.map(() => PAL.ink), prog(t, cue(2) + 1.0, cue(2) + 1.6), [], { crack: prog(t, cue(2) + .7, cue(2) + 1.3) });
          for (let i = 0; i < SLOTS; i++) {
            const w = walker([[.15 + i * .08, SLOT(i) - 1300], [1.9 + i * .05, SLOT(i), E.out]], t, .75, POSES.stand, 1);
            person(g, { x: w.x, y: GY, s: .75, pose: idle(w.pose, t, i), facing: w.facing, color: PAL.ink, seed: i, expr: 'neutral' });
          }
        });
        headline(g, 'HEADLINE FROM THE SCRIPT', 960, 230, prog(t, cue(2), cue(2) + 1.1), { align: 'center', size: 96, red: [1] });
      } },
    /* 2. NEXT IDEA (cue 3 ...): open with an iris from the element it grows out of, fully open exactly on its cue:
       { id: 'next', start: cue(3) - TR, end: cue(5) - .001, enter: { type: 'iris', x: 400, y: 640, dur: TR }, ... }
       Reveal a group on its name: const WNAME = wordAt(3, 'Group A'); colour/accessories/label switch at WNAME.
       headlineWords(g, t, ['20%', 'GROUP', 'A'], [wordAt(3, '20'), WNAME, WNAME + .12], 140, 230, { red: [1, 2] }); */
  ];
  // one representative frame per board (absolute seconds) - these are the boards people approve or comment on
  STORYBOARD = [{ t: 1.6, title: 'Cue 1: everyone walks in' }, { t: cue(3) - .3, title: 'Cue 2: the split' }];
  // sound effects on the same clock (whoosh | pop | click | draw | thud | chime), 1-3 per beat
  SFX_CUES = [{ t: cue(2), type: 'draw' }, { t: cue(2) + .7, type: 'thud' }];
  MUSIC.accents = [cue(2)];
  CUES = SRT_TEXT.map((text, i) => ({ start: C[i], end: C[i + 1], text }));
}
